<?php

namespace App\Http\Controllers\Back;

use App\Http\Controllers\Controller;
use App\Models\MembershipRequest;
use App\Models\User;
use Illuminate\Auth\Events\Registered;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;

class MembershipRequestController extends Controller
{
    public function index(Request $request)
    {
        $selectedStatus = (string) $request->query(
            'status',
            MembershipRequest::STATUS_PENDING
        );

        if (!in_array($selectedStatus, [
            MembershipRequest::STATUS_PENDING,
            MembershipRequest::STATUS_APPROVED,
            MembershipRequest::STATUS_REJECTED,
            'all',
        ], true)) {
            $selectedStatus = MembershipRequest::STATUS_PENDING;
        }

        $query = MembershipRequest::query()
            ->with(['province:id,name', 'city:id,name'])
            ->latest('id');

        if ($selectedStatus !== 'all') {
            $query->where('status', $selectedStatus);
        }

        if ($request->filled('search')) {
            $search = trim((string) $request->search);

            $query->where(function ($q) use ($search) {
                $q->where('mobile', 'like', "%{$search}%")
                    ->orWhere('first_name', 'like', "%{$search}%")
                    ->orWhere('last_name', 'like', "%{$search}%")
                    ->orWhere('business_name', 'like', "%{$search}%");
            });
        }

        $membershipRequests = $query->paginate(20)->withQueryString();

        $pendingCount = MembershipRequest::pending()->count();

        return view(
            'back.membership-requests.index',
            compact('membershipRequests', 'pendingCount', 'selectedStatus')
        );
    }

    public function show(MembershipRequest $membershipRequest)
    {
        $membershipRequest->load([
            'reviewer',
            'approvedUser',
            'province:id,name',
            'city:id,name',
        ]);

        return view(
            'back.membership-requests.show',
            compact('membershipRequest')
        );
    }

    public function approve(MembershipRequest $membershipRequest)
    {
        $approved = DB::transaction(function () use ($membershipRequest): bool {
            $membership = MembershipRequest::query()
                ->whereKey($membershipRequest->id)
                ->lockForUpdate()
                ->firstOrFail();

            if (!$membership->isPending()) {
                return false;
            }

            $user = User::where('username', $membership->mobile)->first();

            if (!$user) {
                $user = User::create([
                    'first_name' => $membership->first_name,
                    'last_name' => $membership->last_name,
                    'username' => $membership->mobile,
                    'email' => null,
                    'level' => 'user',
                    'is_active' => true,
                    'password' => Hash::make(Str::random(64)),
                    'verified_at' => now(),
                ]);
            }

            // Approval means this customer is allowed to use the storefront.
            if (!$user->verified_at) {
                $user->forceFill([
                    'verified_at' => now(),
                ])->save();
            }

            $membership->update([
                'status' => MembershipRequest::STATUS_APPROVED,
                'reject_reason' => null,
                'reviewed_by' => auth()->id(),
                'reviewed_at' => now(),
                'approved_user_id' => $user->id,
            ]);

            return true;
        });

        if (!$approved) {
            toastr()->warning('این درخواست قبلاً بررسی شده است.');

            return redirect()->route('admin.membership-requests.index');
        }

        /*
        |--------------------------------------------------------------------------
        | Sync approved customer with INV
        |--------------------------------------------------------------------------
        |
        | The existing Registered event already has SyncUserToINV attached to it.
        | We fire it only after the membership approval transaction has completed.
        |
        */

        $membershipRequest->refresh();

        if ($membershipRequest->approvedUser) {
            event(new Registered($membershipRequest->approvedUser));
        }

        toastr()->success('درخواست عضویت با موفقیت تأیید شد.');

        return redirect()->route('admin.users.index');
    }

    public function getMiddleware() {
        return parent::getMiddleware(); // TODO: Change the autogenerated stub
    }

    protected function normalizeGuessedAbilityName( $ability ) {}

    public function reject(
        MembershipRequest $membershipRequest,
        Request $request
    ) {
        $request->validate([
            'reject_reason' => ['required', 'string', 'max:1000'],
        ], [
            'reject_reason.required' => 'دلیل رد درخواست را وارد کنید.',
        ]);

        DB::transaction(function () use ($membershipRequest, $request) {
            $membership = MembershipRequest::query()
                ->whereKey($membershipRequest->id)
                ->lockForUpdate()
                ->firstOrFail();

            if (!$membership->isPending()) {
                return;
            }

            $membership->update([
                'status' => MembershipRequest::STATUS_REJECTED,
                'reject_reason' => trim($request->reject_reason),
                'reviewed_by' => auth()->id(),
                'reviewed_at' => now(),
                'approved_user_id' => null,
            ]);
        });

        toastr()->success('درخواست عضویت رد شد.');

        return redirect()->route(
            'admin.membership-requests.show',
            $membershipRequest
        );
    }
}
